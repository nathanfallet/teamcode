// The desktop app (macOS, Windows, Linux): the shared app of :companion, plus what only makes sense on a member's
// computer — the CLI's account, finding the CLI, sessions on this device and their supervision, the menu bar icon.
kotlin { jvmToolchain(21) }

// The SHA-256 of the release's install scripts, given by the release pipeline once they are generated
// (-PteamcodeInstallShSha256=…, -PteamcodeInstallPs1Sha256=…): "Install" runs a script only when its bytes match.
// A build without them (development, a fork) shows the install command instead.
val installerHashes = listOf("teamcodeInstallShSha256", "teamcodeInstallPs1Sha256").associateWith { name ->
    providers.gradleProperty(name).orNull?.also { require(Regex("[0-9a-f]{64}").matches(it)) { "$name must be a lowercase SHA-256." } }
}
val generatedBuildInfo = layout.buildDirectory.dir("generated/desktop-build-info")
val generateDesktopBuildInfo by tasks.registering {
    val version = project.version.toString()
    inputs.property("version", version)
    inputs.property("hashes", installerHashes.mapValues { it.value.orEmpty() })
    outputs.dir(generatedBuildInfo)
    doLast {
        fun literal(value: String?) = value?.let { "\"$it\"" } ?: "null"
        val output = generatedBuildInfo.get().file("me/nathanfallet/teamcode/companion/desktop/DesktopBuildInfo.kt").asFile
        output.parentFile.mkdirs()
        output.writeText(
            "package me.nathanfallet.teamcode.companion.desktop\n\n" +
                "/** Generated by the build: the app's version and the install scripts it may run. */\n" +
                "internal object DesktopBuildInfo {\n" +
                "    const val VERSION: String = \"$version\"\n" +
                "    val INSTALL_SH_SHA256: String? = ${literal(installerHashes["teamcodeInstallShSha256"])}\n" +
                "    val INSTALL_PS1_SHA256: String? = ${literal(installerHashes["teamcodeInstallPs1Sha256"])}\n" +
                "}\n",
        )
    }
}
sourceSets.main { kotlin.srcDir(generateDesktopBuildInfo) }

// The app's own version, readable without starting it: `teamcode ui` reads this file inside an installed app
// (Contents/app/resources on macOS, app/resources on Windows, lib/app/resources on Linux) to know whether it is
// older than the CLI.
val generatedAppResources = layout.buildDirectory.dir("generated/desktop-app-resources")
val generateAppResources by tasks.registering {
    val version = project.version.toString()
    inputs.property("version", version)
    outputs.dir(generatedAppResources)
    doLast {
        val output = generatedAppResources.get().file("common/teamcode-desktop-version").asFile
        output.parentFile.mkdirs()
        output.writeText("$version\n")
    }
}
tasks.matching { it.name == "prepareAppResources" }.configureEach { dependsOn(generateAppResources) }

